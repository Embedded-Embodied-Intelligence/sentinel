            f"{ci('RQfourVsNoReactionOnTimeSentinelJthirty')} pp); J60: "
            f"{m['RQfourOnTimeSentinelJsixty']} / {m['RQfourOnTimeFullResolveJsixty']} / "
            f"{m['RQfourOnTimeNoReactionJsixty']} % "
