"""The README section "Results at a glance" (WP8): every number a macro of the committed
`paper/generated/numbers.tex`, and the committed README equal to the section built from it."""

from pathlib import Path

import pytest

from sentinel.experiments.readme import BEGIN, END, read_macros, section, update

REPO_ROOT = Path(__file__).resolve().parents[1]
NUMBERS = REPO_ROOT / "paper" / "generated" / "numbers.tex"


def test_the_committed_readme_shows_the_committed_macros(tmp_path: Path) -> None:
    readme = tmp_path / "README.md"
    readme.write_bytes((REPO_ROOT / "README.md").read_bytes())
    assert update(readme, NUMBERS) is False  # regenerated by `sentinel paper`, not edited
    macros = read_macros(NUMBERS)
    assert len(macros) == 1430
    text = section(macros)
    for name in ("RQfourOnTimeSentinelJthirty", "RQtwoGapCpsatTenJthirty", "RQfiveEventMessages"):
        assert macros[name] in text


def test_macro_values_become_plain_text_and_the_section_is_replaced(tmp_path: Path) -> None:
    numbers = tmp_path / "numbers.tex"
    numbers.write_text(
        "% a comment\n\\newcommand{\\A}{\\ensuremath{-}1.5}\n\\newcommand{\\B}{75{,}486}\n",
        encoding="utf-8",
    )
    assert read_macros(numbers) == {"A": "\u22121.5", "B": "75,486"}
    readme = tmp_path / "README.md"
    readme.write_text(f"# Title\n\n{BEGIN}\nold\n{END}\n\nRest.\n", encoding="utf-8")
    assert update(readme, NUMBERS) is True and update(readme, NUMBERS) is False
    text = readme.read_text(encoding="utf-8")
    assert text.startswith("# Title\n\n" + BEGIN) and text.endswith(END + "\n\nRest.\n")
    assert "old" not in text and "| RQ4 on time" in text
    (tmp_path / "plain.md").write_text("# No markers\n", encoding="utf-8")
    with pytest.raises(ValueError, match="no <!-- results:begin -->"):
        update(tmp_path / "plain.md", NUMBERS)
